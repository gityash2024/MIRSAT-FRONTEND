import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { parse } from '@babel/parser';
import { INLINE_STYLE_COLORS, SVG_ATTRIBUTE_COLORS } from '../src/theme/inlineColorList.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const tokenPattern = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b|var\(--color-[a-z-]+\)/gi;
const normalize = value => value.toLowerCase().replace(/\s+/g, ' ').replace(/\(\s+/, '(').replace(/\s+\)/, ')').replace(/\s*,\s*/g, ', ');
const files = directory => fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory()
  ? entry.name === 'theme' ? [] : files(path.join(directory, entry.name))
  : /\.jsx?$/.test(entry.name) && !/\.(test|spec)\.|backup|\.bak/.test(entry.name) ? [path.join(directory, entry.name)] : []);

// Include quoted values held in maps/conditional expressions as well as direct
// style properties. A value may be reused for different roles; the adapter
// interprets it by the actual DOM property, not by where the constant lives.
export function collectInlineColors(project = root) {
  const colors = { bg: new Set(), text: new Set(), border: new Set() };
  const propertyRole = property => /^(background|backgroundColor|backgroundImage|bg|bgColor|accentColor)$/.test(property) ? 'bg'
    : /^(color|fill|stroke|textColor|caretColor)$/.test(property) ? 'text'
      : /^(border|outline)(Top|Right|Bottom|Left)?(Color)?$/.test(property) ? 'border' : null;
  const visit = (node, inheritedRole) => {
    if (!node || typeof node !== 'object') return;
    const name = node.type === 'ObjectProperty' ? node.key?.name || node.key?.value
      : node.type === 'JSXAttribute' ? node.name?.name : null;
    const role = propertyRole(name || '') || inheritedRole;
    if (node.type === 'StringLiteral') (node.value.match(tokenPattern) || []).forEach(color =>
      (role ? [role] : ['bg', 'text']).forEach(target => colors[target].add(normalize(color))));
    for (const [key, value] of Object.entries(node)) {
      if (['loc', 'extra', 'comments', 'tokens'].includes(key)) continue;
      if (Array.isArray(value)) value.forEach(child => visit(child, role));
      else if (value && typeof value === 'object') visit(value, role);
    }
  };
  for (const file of files(path.join(project, 'src'))) visit(parse(fs.readFileSync(file, 'utf8'), { sourceType: 'unambiguous', plugins: ['jsx'] }));
  return Object.fromEntries(Object.entries(colors).map(([role, values]) => [role, [...values].sort()]));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const colors = collectInlineColors();
  const inventory = Object.fromEntries(['bg', 'text', 'border'].map(role => [role,
    [...new Set([...INLINE_STYLE_COLORS[role], ...colors[role]])].sort(),
  ]));
  if (process.argv[2] === '--write') {
    fs.writeFileSync(path.join(root, 'src/theme/inlineColorList.js'),
      '// Generated by npm run theme:colors. Retains legacy/server-supplied colors.\n'
      + '// All property roles are checked; the runtime maps only the role actually used.\n'
      + `export const INLINE_STYLE_COLORS = ${JSON.stringify(inventory, null, 2)};\n\n`
      + `export const SVG_ATTRIBUTE_COLORS = ${JSON.stringify(SVG_ATTRIBUTE_COLORS, null, 2)};\n`);
  } else if (process.argv[2]) fs.writeFileSync(process.argv[2], JSON.stringify(inventory, null, 2));
  else throw new Error('Use --write to refresh the inventory, or provide an output JSON path.');
  console.log(`Inline theme coverage: ${inventory.bg.length}/${inventory.text.length}/${inventory.border.length} background/text/border entries.`);
}
